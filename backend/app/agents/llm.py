# 3. Fake / Mock LLM Provider (Offline Testing & Benchmarking)
# =============================================================================

class FakeLLMProvider(LLMProvider):
    """Deterministic test double for testing without external network or API keys.

    Allows programming custom responses, schema returns, and simulated failures (timeouts,
    network crashes, malformed JSON).
    """

    def __init__(
        self,
        canned_responses: Optional[Dict[str, Any]] = None,
        canned_text: str = "Simulated response from FakeLLMProvider",
        model_name: str = "fake-marine-llm-v1",
        simulate_timeout: bool = False,
        simulate_failure: bool = False,
        simulate_malformed: bool = False,
    ) -> None:
        self.canned_responses = canned_responses or {}
        self.canned_text = canned_text
        self._model_name = model_name
        self.simulate_timeout = simulate_timeout
        self.simulate_failure = simulate_failure
        self.simulate_malformed = simulate_malformed
        self.call_history: List[Dict[str, Any]] = []

    def set_canned_structured_response(self, response_obj: BaseModel) -> None:
        """Helper to program a specific canned structured response for testing."""
        schema_name = type(response_obj).__name__
        self.canned_responses[schema_name] = response_obj

    @property
    def provider_name(self) -> str:
        return "fake"

    @property
    def model_name(self) -> str:
        return self._model_name

    def generate(
        self,
        messages: List[LLMMessage],
        temperature: float = 0.0,
        max_tokens: int = 1024,
        timeout_seconds: Optional[float] = None,
    ) -> LLMResponse:
        self.call_history.append({
            "operation": "generate",
            "messages": messages,
            "temperature": temperature,
            "max_tokens": max_tokens,
        })

        if self.simulate_timeout:
            raise TimeoutError("Simulated LLM call deadline exceeded (timeout).")
        if self.simulate_failure:
            raise RuntimeError("Simulated LLM service connection error.")

        return LLMResponse(
            content=self.canned_text,
            token_usage=TokenUsage(prompt_tokens=15, completion_tokens=25, total_tokens=40),
            finish_reason="stop",
        )

    def generate_structured(
        self,
        messages: List[LLMMessage],
        response_schema: Type[T],
        temperature: float = 0.0,
        timeout_seconds: Optional[float] = None,
    ) -> T:
        self.call_history.append({
            "operation": "generate_structured",
            "schema": response_schema.__name__,
            "messages": messages,
            "temperature": temperature,
        })

        if self.simulate_timeout:
            raise TimeoutError("Simulated LLM structured call deadline exceeded.")
        if self.simulate_failure:
            raise RuntimeError("Simulated LLM provider exception.")
        if self.simulate_malformed:
            # Attempt to validate an empty or malformed dictionary
            return response_schema.model_validate({"_invalid_field_force_error": True})

        schema_key = response_schema.__name__
        if schema_key in self.canned_responses:
            data = self.canned_responses[schema_key]
            if callable(data):
                res = data(messages)
                if isinstance(res, dict):
                    return response_schema.model_validate(res)
                elif isinstance(res, response_schema):
                    return res
                return res
            elif isinstance(data, dict):
                return response_schema.model_validate(data)
            elif isinstance(data, response_schema):
                return data

        if schema_key == "LLMResponseDraft":
            return response_schema.model_validate({
                "synthesized_text": self.canned_text,
                "key_factors_cited": [],
                "language": "en",
            })

        if schema_key == "IntentExtractionResult":
            # Provide sensible fallback for mock tests that test downstream response composition
            user_text = ""
            for m in messages:
                if getattr(m, "role", None) == MessageRole.USER:
                    user_text = m.content
            from backend.app.agents.intent import IntentCategory
            msg_l = user_text.lower()
            if any(k in msg_l for k in ["safe", "safety", "sail", "depart", "leave", "fish"]):
                canned_intent = IntentCategory.SAFETY
            elif any(k in msg_l for k in ["pfz", "matsya"]):
                canned_intent = IntentCategory.PFZ
            elif any(k in msg_l for k in ["hazard", "storm", "cyclone", "restricted", "geofence"]):
                canned_intent = IntentCategory.HAZARDS
            elif any(k in msg_l for k in ["route", "passage"]):
                canned_intent = IntentCategory.ROUTE
            elif any(k in msg_l for k in ["why", "explain", "reason"]):
                canned_intent = IntentCategory.ANALYTICAL_EXPLANATION
            else:
                canned_intent = IntentCategory.SAFETY
            from backend.app.agents.intent import detect_language
            detected_lang = detect_language(user_text)
            return response_schema.model_validate({
                "intent": canned_intent,
                "confidence": 0.95,
                "detected_language": detected_lang,
                "entities": {"origin_harbor": "Ratnagiri" if "ratnagiri" in msg_l else None},
            })

        # Fallback: construct default model instance if fields allow defaults
        try:
            return response_schema.model_validate({})
        except Exception:
            # If schema requires fields, return reasonable canned mock data
            return response_schema.model_construct()



